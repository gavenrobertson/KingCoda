import { chipAlpha, dark, fonts, heatmap, light, radius, type Palette } from './tokens.ts';

function vars(p: Palette, scale: readonly string[], indent: string): string {
  const lines = Object.entries(p).map(([k, v]) => `${indent}--kc-${k}: ${v};`);
  scale.forEach((v, i) => lines.push(`${indent}--kc-heat-${i}: ${v};`));
  return lines.join('\n');
}

/** Builds the theme stylesheet: CSS variables per theme plus a Tailwind v4 `@theme` mapping. */
export function buildThemeCss(): string {
  const colorNames = Object.keys(dark);
  const themeColors = [
    ...colorNames.map((k) => `  --color-${k}: var(--kc-${k});`),
    ...heatmap.dark.map((_, i) => `  --color-heat-${i}: var(--kc-heat-${i});`),
  ].join('\n');
  const radii = Object.entries(radius)
    .map(([k, v]) => `  --radius-kc-${k}: ${v};`)
    .join('\n');
  const pct = Math.round(chipAlpha * 100);

  return `/* GENERATED by packages/ui/scripts/build-css.ts from src/tokens.ts — do not edit by hand. */

:root,
:root[data-theme='dark'] {
  color-scheme: dark;
${vars(dark, heatmap.dark, '  ')}
}

:root[data-theme='light'] {
  color-scheme: light;
${vars(light, heatmap.light, '  ')}
}

@media (prefers-color-scheme: light) {
  :root[data-theme='system'] {
    color-scheme: light;
${vars(light, heatmap.light, '    ')}
  }
}

@theme inline {
${themeColors}
  --color-easy-chip: color-mix(in srgb, var(--kc-easy) ${pct}%, transparent);
  --color-medium-chip: color-mix(in srgb, var(--kc-medium) ${pct}%, transparent);
  --color-hard-chip: color-mix(in srgb, var(--kc-hard) ${pct}%, transparent);
  --font-display: ${fonts.display};
  --font-sans: ${fonts.sans};
  --font-mono: ${fonts.mono};
${radii}
}
`;
}
